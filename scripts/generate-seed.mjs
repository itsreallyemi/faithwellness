// Builds supabase/seed.sql from supabase/seed-data.json.
// Run: npm run seed:sql
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const data = JSON.parse(readFileSync(new URL("supabase/seed-data.json", root), "utf8"));

// Stable ids so re-running the seed doesn't create duplicates.
const uuid = (key) => {
  const h = createHash("md5").update(`faithwellness:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (xs) => (xs.length ? `array[${xs.map(q).join(", ")}]::text[]` : "'{}'::text[]");

const out = [
  "-- Generated by scripts/generate-seed.mjs from supabase/seed-data.json. Do not edit by hand.",
  "-- FICTIONAL sample counselors. Replace before launch.",
  "",
];

for (const [i, f] of data.focusAreas.entries()) {
  out.push(
    `insert into public.focus_areas (slug, label, sort, featured) values (${q(f.slug)}, ${q(f.label)}, ${i}, ${f.featured})` +
      ` on conflict (slug) do update set label = excluded.label, sort = excluded.sort, featured = excluded.featured;`,
  );
}
out.push("");

for (const c of data.churches) {
  out.push(
    `insert into public.churches (id, slug, name, city, denomination) values (${q(uuid(`church:${c.slug}`))}, ${q(c.slug)}, ${q(c.name)}, ${q(c.city)}, ${q(c.denomination)})` +
      ` on conflict (slug) do update set name = excluded.name, city = excluded.city, denomination = excluded.denomination;`,
  );
}
out.push("");

for (const c of data.counselors) {
  const id = uuid(`counselor:${c.slug}`);
  out.push(`-- ${c.name}`);
  out.push(
    `insert into auth.users (id, instance_id, aud, role, email, raw_app_meta_data, raw_user_meta_data, created_at, updated_at)` +
      ` values (${q(id)}, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', ${q(`${c.slug}@example.test`)}, '{}', '{}', now(), now())` +
      ` on conflict (id) do nothing;`,
  );
  out.push(
    `insert into public.profiles (id, role, full_name, avatar_url, time_zone) values (${q(id)}, 'counselor', ${q(c.name)}, ${q(c.avatarUrl)}, ${q(c.timeZone)})` +
      ` on conflict (id) do update set role = 'counselor', full_name = excluded.full_name, avatar_url = excluded.avatar_url, time_zone = excluded.time_zone;`,
  );
  const cols = {
    id: q(id),
    slug: q(c.slug),
    preferred_name: q(c.preferredName),
    title: q(c.title),
    church_id: `(select id from public.churches where slug = ${q(c.church)})`,
    years_ministry: c.yearsMinistry,
    languages: arr(c.languages),
    summary: q(c.summary),
    about: q(c.about.join("\n\n")),
    approach: q(c.approach),
    verse: q(c.verse),
    verse_ref: q(c.verseRef),
    help_with: arr(c.helpWith),
    badges: arr(c.badges),
    insurance_accepted: arr(c.insurance ?? []),
    fee_30_cents: c.fee30Cents,
    fee_60_cents: c.fee60Cents,
    offers_30: c.offers30,
    offers_60: c.offers60,
    sliding_scale: c.slidingScale,
    free_for_members: c.freeForMembers,
    fee_note: q(c.feeNote),
    avatar_tint: q(c.avatarTint),
    is_published: true,
  };
  const names = Object.keys(cols);
  out.push(
    `insert into public.counselors (${names.join(", ")}) values (${Object.values(cols).join(", ")})` +
      ` on conflict (id) do update set ${names.filter((n) => n !== "id").map((n) => `${n} = excluded.${n}`).join(", ")};`,
  );
  out.push(`delete from public.credentials where counselor_id = ${q(id)};`);
  for (const [i, cr] of c.credentials.entries()) {
    out.push(
      `insert into public.credentials (counselor_id, label, issuer, year, sort) values (${q(id)}, ${q(cr.label)}, ${q(cr.issuer)}, ${cr.year ?? "null"}, ${i});`,
    );
  }
  out.push(`delete from public.counselor_focus_areas where counselor_id = ${q(id)};`);
  for (const f of c.focusAreas) {
    out.push(`insert into public.counselor_focus_areas (counselor_id, focus_area_slug) values (${q(id)}, ${q(f)});`);
  }
  out.push(`delete from public.availability_rules where counselor_id = ${q(id)};`);
  for (const r of c.availability) {
    out.push(
      `insert into public.availability_rules (counselor_id, weekday, start_time, end_time) values (${q(id)}, ${r.weekday}, ${q(r.start)}, ${q(r.end)});`,
    );
  }
  out.push("");
}

writeFileSync(new URL("supabase/seed.sql", root), out.join("\n"));
console.log(`Wrote supabase/seed.sql (${data.counselors.length} counselors)`);
